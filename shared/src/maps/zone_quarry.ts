/**
 * 采石场区。
 *
 * 这是全图唯一"往上爬"的区域：三层阶梯石台（1.2 / 2.4 / 3.6m），每一层都必须
 * 走 0.4m 的台阶上去 —— 直接跳上 1.2m 是不行的，这也是这一区的玩法核心：
 * 想拿高地就得走固定的三条坡道，而坡道口是全图最容易被预瞄的地方。
 *
 * 设计要点：
 * - 阶梯不是造型而是**节奏**：三层台面各自只能看到下一层的边沿，站在最上层
 *   能俯视采石坑底，但看不到坑外 —— 高地有收益，也有盲区。
 * - 吊臂（10.6m）是这一区的垂直断点：一根铁塔 + 一根 12m 的横臂，横臂在
 *   半空中把"坑口到东侧走廊"的斜向视线切了一刀。
 * - 碎石堆是低矮的 0.4/0.8m 石块，用确定性 RNG 摆，数量显式可调：它们的作用
 *   是打碎地面上的直线（子弹能过去，眼睛不会一眼看到 40m 外）。
 * - 石台全部是实心块，不做内部空间：采石场不需要房间，需要的是高度层次。
 */

import { BrushSet, translate, mulberry32 } from './kit.ts'

export interface QuarryOpts {
  /** 碎石堆数量。每堆 1 个盒子。默认 56。 */
  rubble?: number
  seed?: number
}

export function buildQuarry(set: BrushSet, ox: number, oz: number, opts: QuarryOpts = {}): void {
  const s = new BrushSet()
  const rnd = mulberry32(opts.seed ?? 0x9e3779b9)
  const rubble = opts.rubble ?? 56

  // ---- 三层阶梯石台：12×8 / 9×6 / 6×4，实心，层层收分 ----
  s.slab(0, -6, 12.0, 8.0, 0, 1.2, 'stone') // 第一层台面 1.2m
  s.slab(0, -6, 9.0, 6.0, 1.2, 2.4, 'stone') // 第二层 2.4m
  s.slab(0, -6, 6.0, 4.0, 2.4, 3.6, 'stone') // 第三层 3.6m
  // 每层边沿的矮胸墙：站上去能架枪，但不会把整个台面暴露成"平台靶"
  s.slab(0, 1.6, 12.0, 0.4, 1.2, 2.0, 'stone')
  s.slab(0, -0.4, 9.0, 0.4, 2.4, 3.2, 'stone')
  s.slab(0, -2.4, 6.0, 0.4, 3.6, 4.4, 'stone')

  // ---- 上台阶：三层坡道，每一级的前后高差严格 0.4m ----
  // 西侧坡道：地面 0 → 1.2m，三级，落点正对第一层台面西沿（x = -12）
  s.stairX(-6, -15.6, 1, 3, 4.0, 'stone', 1.2)
  // 第一层 1.2 → 第二层 2.4：三级踏板坐在台面上（底面 1.2），一阶 0.4m
  for (let i = 0; i < 3; i++) s.slab(-11.5 + i, -6, 0.5, 2.0, 1.2, 1.6 + i * 0.4, 'stone')
  // 第二层 2.4 → 第三层 3.6：同样三级，踏板底面 2.4
  for (let i = 0; i < 3; i++) s.slab(-8.5 + i, -6, 0.5, 1.6, 2.4, 2.8 + i * 0.4, 'stone')

  // ---- 吊臂：铁塔 10.6m + 12m 横臂 ----
  s.slab(16, -16, 1.2, 1.2, 0, 10.0, 'metal') // 塔身
  s.slab(16, -16, 2.0, 2.0, 0, 0.4, 'stone') // 塔座
  s.span(16, 10.4, -16, 6.2, 0.3, 0.5, 'metal', 0.3) // 横臂（斜 17°，指向坑口）
  s.span(16, 10.4, -16, 2.2, 0.25, 1.4, 'metal') // 平衡臂
  s.slab(11.4, -13.4, 0.9, 0.9, 0, 0.8, 'metal') // 地面上的配重块
  s.span(21.4, 6.2, -17.6, 0.08, 4.0, 0.08, 'metal') // 吊索（细，纯造型）
  s.span(21.4, 2.4, -17.6, 0.6, 0.6, 0.6, 'metal') // 吊钩下的石块

  // ---- 石料堆：手写的大块，界定坑口范围 ----
  s.slab(-18, 8, 4.0, 3.0, 0, 1.2, 'stone')
  s.slab(-18, 12.4, 2.4, 3.0, 0, 0.8, 'stone')
  s.slab(18, 6, 3.0, 4.0, 0, 1.6, 'stone')
  s.slab(22, 10, 2.0, 2.0, 0, 0.4, 'stone')
  s.slab(-4, 18, 8.0, 2.0, 0, 2.0, 'stone') // 南侧料墙：把坑口和南边大路彻底分开
  s.slab(-24, -2, 2.0, 6.0, 0, 2.4, 'stone') // 西侧挡土墙
  s.slab(24, -22, 3.0, 3.0, 0, 3.2, 'stone') // 东北角的碎石山

  // ---- 工具棚：采石场唯一能关门的室内空间 ----
  // 放在坑口西北角，避开三层台面与吊臂；碎石生成也要绕开它。
  s.wallZ(-22, -24, -16, 0, 2.8, { t: 0.4, material: 'wood' }) // 西墙
  s.wallZ(-14, -24, -16, 0, 2.8, {
    t: 0.4,
    material: 'wood',
    windows: [{ gap: [-21.4, -19.4], sill: 1.2, top: 2.4 }],
  }) // 东墙 + 窗
  s.wallX(-24, -22, -14, 0, 2.8, {
    t: 0.4,
    material: 'wood',
    windows: [{ gap: [-19.4, -17.4], sill: 1.2, top: 2.4 }],
  }) // 北墙 + 窗
  s.wallX(-16, -22, -14, 0, 2.8, { t: 0.4, material: 'wood', gaps: [[-19.0, -16.6]] }) // 南门
  s.span(-18, 3.0, -20, 4.4, 0.2, 4.4, 'wood') // 平顶
  s.slab(-20.4, -22.4, 1.2, 0.5, 0, 0.8, 'wood') // 工作台
  s.slab(-15.6, -17.2, 0.6, 0.6, 0, 1.2, 'wood') // 木箱
  s.slab(-20.8, -17.0, 0.5, 0.5, 0, 1.6, 'metal') // 油桶

  // ---- 碎石堆：确定性 RNG，数量显式可调 ----
  for (let i = 0; i < rubble; i++) {
    const x = -26 + rnd() * 52
    const z = -26 + rnd() * 52
    if (Math.abs(x) < 16.4 && z > -15 && z < 3) continue // 三层台面
    if (Math.abs(x - 16) < 3 && Math.abs(z + 16) < 3) continue // 吊臂塔
    if (Math.abs(x + 4) < 9.4 && Math.abs(z - 18) < 2.6) continue // 南料墙
    if (Math.abs(x + 18) < 4.8 && Math.abs(z + 20) < 4.8) continue // 工具棚
    const tall = rnd() < 0.4
    s.slab(x, z, 0.6 + rnd() * 1.4, 0.6 + rnd() * 1.4, 0, tall ? 0.8 : 0.4, 'stone')
  }

  // ---- 作业痕迹：noCollide 的料道与车辙（0.08m）----
  for (let i = 0; i < 10; i++) {
    s.decal(-24 + rnd() * 46, 2 + rnd() * 22, 1.0 + rnd() * 1.6, 0.35 + rnd() * 0.3, 'stone')
  }

  set.list.push(...translate(s.list, ox, oz))
}
