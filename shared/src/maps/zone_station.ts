/**
 * 火车站废墟区。
 *
 * 这一区是全图唯一的"长条"：一条 110m 的站场横躺在南侧，用月台（1.2m）和
 * 三节翻倒的车厢把它劈成两条互相看不见的走廊。这是整张图上最刻意的
 * **长视线终结者** —— 如果没有它，从西侧沼泽一路到东侧采石场会有一条
 * 150m 的通视带，那是这一版最不能出现的东西。
 *
 * 设计要点：
 * - 铁轨与枕木是 noCollide 的地面贴片：站场地面要平，玩家不该被 0.12m 的
 *   钢轨绊住；真正的障碍只有月台、车厢和信号塔。
 * - 月台抬到 1.2m，两端各有三级 0.4m 台阶：上下月台必须走坡道，站台就成了
 *   一个"有门的高地"，而不是谁都能跳上去的矮台。
 * - 三节车厢摆成三种角度（正放 / 侧翻 / 斜插），侧翻那节是最硬的掩体：
 *   它挡住的是一条 13m 的斜线，而正放的车厢只挡住一条 3m 的横线。
 * - 煤堆用确定性 RNG 摆，数量显式可调，只到 0.8m：能藏下身，挡不住视线。
 */

import { BrushSet, translate, mulberry32 } from './kit.ts'

export interface StationOpts {
  /** 煤堆数量。每堆 1 个盒子。默认 30。 */
  coal?: number
  seed?: number
}

export function buildStation(set: BrushSet, ox: number, oz: number, opts: StationOpts = {}): void {
  const s = new BrushSet()
  const rnd = mulberry32(opts.seed ?? 0x51a7e11)
  const coal = opts.coal ?? 30

  // ---- 站场地面：双轨 + 枕木，全部 noCollide（只做视觉与脚步线）----
  s.decal(0, -6.7, 54, 0.09, 'metal', 0.12)
  s.decal(0, -5.3, 54, 0.09, 'metal', 0.12)
  for (let x = -52; x <= 52; x += 2.4) s.decal(x, -6, 0.12, 1.4, 'wood', 0.1)

  // ---- 月台：34 × 6，抬到 1.2m，两端各三级 0.4m 台阶 ----
  s.slab(0, 5, 17.0, 3.0, 0, 1.2, 'wood')
  s.stairZ(-13, 9.2, -1, 3, 6.0, 'wood', 1.2) // 西端坡道
  s.stairZ(13, 9.2, -1, 3, 6.0, 'wood', 1.2) // 东端坡道
  s.slab(0, 1.6, 17.0, 0.4, 1.2, 1.6, 'wood') // 月台边沿的防滑矮条

  // ---- 站台雨棚：四根立柱 + 两段屋顶，中间塌掉一段 ----
  for (const x of [-14, -2, 10, 20]) s.slab(x, 3.4, 0.3, 0.3, 1.2, 4.8, 'metal')
  s.span(-9, 5.0, 4.6, 9.0, 0.2, 2.6, 'metal') // 西段屋顶
  s.span(15, 5.0, 4.6, 7.0, 0.2, 2.6, 'metal') // 东段屋顶
  s.slab(-2, 3.4, 0.3, 0.3, 4.8, 5.6, 'metal') // 塌下来的檩条（悬空一段，抬头能看见"断了"）

  // ---- 三节车厢：正放 / 侧翻 / 斜插 ----
  s.slabR(-16, -6, 7.0, 1.6, 0, 3.2, 0.05, 'metal') // 第一节：正放，挡住 3m 的横线
  s.slabR(-16, -6, 6.6, 1.4, 3.2, 3.6, 0.05, 'metal') // 车顶
  s.slabR(-23.4, -6, 0.6, 1.6, 0, 3.2, 0.05, 'metal') // 车尾端板
  s.slabR(14, -9, 6.0, 1.6, 0, 1.6, -0.5, 'metal') // 第二节：侧翻，13m 斜线掩体
  s.slabR(14, -9, 5.6, 0.4, 1.6, 2.0, -0.5, 'metal') // 侧翻车厢朝上的一侧（车轮架）
  s.slabR(34, -3, 5.6, 1.6, 0, 2.8, 0.35, 'metal') // 第三节：斜插进煤场的车皮
  s.slabR(34, -3, 5.2, 1.4, 2.8, 3.2, 0.35, 'metal')
  // 脱落的轮对：三只 1.6m 的金属盘，蹲下能藏
  s.slabR(-8, -8.4, 0.8, 0.8, 0, 1.6, 0.2, 'metal')
  s.slabR(20, -12, 0.8, 0.8, 0, 1.6, -0.3, 'metal')
  s.slabR(8, -6.2, 0.8, 0.8, 0, 1.6, 0.9, 'metal')

  // ---- 信号塔：四腿 + 三层横梁，12m 高 ----
  const legs: [number, number][] = [[46, 0], [49.2, 0], [46, 3.2], [49.2, 3.2]]
  for (const [x, z] of legs) s.slab(x, z, 0.2, 0.2, 0, 12.0, 'metal')
  for (const y of [3.2, 6.4, 9.6]) {
    s.span(47.6, y, 0, 1.6, 0.12, 0.12, 'metal')
    s.span(47.6, y, 3.2, 1.6, 0.12, 0.12, 'metal')
    s.span(46, y, 1.6, 0.12, 0.12, 1.6, 'metal')
    s.span(49.2, y, 1.6, 0.12, 0.12, 1.6, 'metal')
  }
  s.span(47.6, 12.4, 1.6, 2.0, 1.2, 1.6, 'metal') // 信号室
  s.slab(47.6, 1.6, 2.4, 2.4, 0, 1.2, 'stone') // 塔基座

  // ---- 站房废墟：12 × 8，墙 3.6m，屋顶塌了一半 ----
  s.wallZ(-40, 8, 16, 0, 3.6, { t: 0.6, material: 'stone' })
  s.wallZ(-28, 8, 16, 0, 3.6, { t: 0.6, material: 'stone' })
  s.wallX(8, -40, -28, 0, 3.6, { t: 0.6, material: 'stone', gaps: [[-36, -32]] }) // 南门 4m
  s.wallX(16, -40, -28, 0, 3.6, { t: 0.6, material: 'stone' })
  s.span(-37, 3.8, 12, 3.2, 0.2, 4.2, 'wood') // 没塌的那半片屋顶（底面 3.6m）
  s.slab(-34, 10, 1.2, 0.8, 0, 0.8, 'wood') // 售票台

  // ---- 煤场：车皮旁的煤堆，数量显式可调 ----
  for (let i = 0; i < coal; i++) {
    const x = 6 + rnd() * 46
    const z = -20 + rnd() * 16
    if (Math.abs(x - 14) < 7.6 && Math.abs(z + 9) < 3.4) continue // 侧翻车厢
    if (Math.abs(x - 34) < 6.6 && Math.abs(z + 3) < 3.6) continue // 斜插车皮
    if (x > 44 && z > -2) continue // 信号塔
    s.slab(x, z, 0.9 + rnd() * 1.3, 0.9 + rnd() * 1.3, 0, rnd() < 0.5 ? 0.4 : 0.8, 'mud')
  }

  // ---- 站台尽头的堆货：木箱与铁桶，给站台两端各一个硬掩体 ----
  s.slab(-18, 5, 1.2, 1.2, 1.2, 2.8, 'wood')
  s.slab(17, 5, 1.0, 1.0, 1.2, 2.4, 'metal')
  s.slab(-24, 5, 1.6, 1.6, 0, 1.2, 'wood')
  s.slab(24, 5, 1.4, 1.4, 0, 1.2, 'wood')

  set.list.push(...translate(s.list, ox, oz))
}
