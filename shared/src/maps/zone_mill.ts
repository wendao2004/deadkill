/**
 * 磨坊与谷仓区。
 *
 * 语汇：粗木梁 + 铁皮。风车塔是全图除了钟楼之外最高的东西（12.6m），把它放在
 * 西北角，等于给整个西北象限钉了一根"你在哪"的标尺 —— 玩家不用看地图，
 * 抬头就知道自己是在农舍北面还是磨坊南面。
 *
 * 设计要点：
 * - 谷仓做成实心大块而不是空房间：它是**断视线**用的。空心的谷仓会变成
 *   全图最好的架枪点，而 260m 的图里不需要再多一个高点。
 * - 风车塔底 8×8、中段收成 6×6：收分让塔在半高处产生一道"能绕的边"，
 *   贴塔绕圈的人不会一直暴露在同一个方向上。
 * - 干草打包机是这一区唯一的金属块：它的作用是给"木色谷仓"配一个材质反差，
 *   玩家在墙后一眼就能分清哪块是草、哪块是铁。
 * - 草捆用 RNG 摆（数量显式可调），高度只有 1.2/1.6m 两档：踩着能上，
 *   站着能露头，构成谷仓外围的第二层掩体。
 */

import { BrushSet, translate, mulberry32 } from './kit.ts'

export interface MillOpts {
  /** 草捆数量。每捆 1 个盒子。默认 26。 */
  hays?: number
  seed?: number
}

export function buildMill(set: BrushSet, ox: number, oz: number, opts: MillOpts = {}): void {
  const s = new BrushSet()
  const rnd = mulberry32(opts.seed ?? 0x3b1a77)
  const hays = opts.hays ?? 26

  // ---- 风车塔：底 8×8（0~8m），中段收成 6×6（8~12m），顶帽 12.6m ----
  s.slab(-8, -10, 4.0, 4.0, 0, 8.0, 'stone')
  s.slab(-8, -10, 3.0, 3.0, 8.0, 12.0, 'wood')
  s.span(-8, 12.6, -10, 3.6, 0.6, 3.6, 'metal', Math.PI / 4) // 顶帽（转 45° 的八边形）
  s.slab(-8, -14.6, 1.2, 0.6, 0, 1.2, 'wood') // 塔门外的木台阶：0.4m 一级
  s.slab(-9.4, -14.2, 0.4, 0.4, 0, 2.4, 'wood') // 门框柱
  s.slab(-6.6, -14.2, 0.4, 0.4, 0, 2.4, 'wood') // 门框柱（两根之间 2.8m 的门洞）
  // 风叶：只有 Y 轴旋转的方块，所以用一根横杆 + 一根竖杆拼出十字风叶（漫画式简化）
  s.span(-8, 10.0, -14.6, 5.2, 0.16, 0.16, 'wood')
  s.span(-8, 10.0, -14.6, 0.16, 5.2, 0.16, 'wood')
  s.span(-8, 10.0, -14.9, 0.7, 0.7, 0.4, 'metal') // 轮毂

  // ---- 谷仓：16 × 10 实心块，6m 高 + 双坡屋顶 ----
  s.slab(10, -8, 8.0, 5.0, 0, 6.0, 'wood')
  s.span(10, 6.8, -11, 8.2, 0.8, 3.2, 'wood') // 北坡
  s.span(10, 6.8, -5, 8.2, 0.8, 3.2, 'wood') // 南坡
  s.span(10, 7.6, -8, 8.2, 0.2, 0.3, 'wood') // 屋脊
  s.slab(2.4, -8, 0.4, 2.4, 0, 3.2, 'wood') // 西侧门框（门洞 2.4m 宽）
  s.slab(2.4, -12.6, 0.4, 1.0, 0, 3.2, 'wood')
  s.slab(2.4, -3.4, 0.4, 1.0, 0, 3.2, 'wood')
  s.slab(1.2, -8, 1.4, 2.2, 0, 0.8, 'wood') // 门口装货台 0.8m：站上去能越过门框看进去
  s.slab(5.6, -3.0, 2.0, 0.4, 0, 1.6, 'wood') // 谷仓南墙外的料槽

  // ---- 干草打包机：金属块 + 压杆 + 出料口 ----
  s.slab(-2, 10, 2.4, 1.6, 0, 1.6, 'metal')
  s.span(-2, 2.6, 10, 2.6, 0.25, 0.3, 'metal') // 压杆（悬空）
  s.slab(1.2, 10, 1.2, 1.4, 0, 0.8, 'metal') // 出料口
  s.slab(-4.4, 10, 0.8, 1.2, 0, 0.4, 'metal') // 接料板
  s.slab(-2, 12.2, 2.4, 0.4, 1.6, 2.4, 'metal') // 机身挡板

  // ---- 磨坊主小屋：8 × 6，3.2m 高，南面留门 ----
  s.wallZ(-14, 10, 16, 0, 3.2, { t: 0.4, material: 'wood' })
  s.wallZ(-6, 10, 16, 0, 3.2, { t: 0.4, material: 'wood' })
  s.wallX(10, -14, -6, 0, 3.2, { t: 0.4, material: 'wood', gaps: [[-11.4, -8.6]] }) // 北墙留门 2.8m
  s.wallX(16, -14, -6, 0, 3.2, { t: 0.4, material: 'wood', gaps: [[-11, -7]] }) // 南墙留窗
  s.span(-10, 3.6, 13, 4.2, 0.2, 3.2, 'wood') // 屋顶（底面 3.4m，屋里不撞头）
  s.slab(-10, 11.2, 1.6, 0.4, 0, 0.8, 'wood') // 屋里的矮柜：正对北门蹲着能架枪

  // ---- 院子：石墙围出磨坊前场，只留南侧一个 5m 口 ----
  s.wallX(22, -18, -2, 0, 2.0, { t: 0.6, material: 'stone' })
  s.wallZ(-18, 6, 22, 0, 2.0, { t: 0.6, material: 'stone' })
  s.wallZ(20, 6, 22, 0, 2.0, { t: 0.6, material: 'stone' })

  // ---- 草捆：数量显式可调，1.2 / 1.6 两档 ----
  const rolls: [number, number][] = [[4, 16], [-8, 18], [16, 4], [-16, -2], [12, 20], [-20, 12]]
  for (const [x, z] of rolls) s.hay(x, z, 1.6, 1.6, rnd() < 0.5 ? 1.2 : 1.6)
  for (let i = 0; i < hays; i++) {
    const x = -24 + rnd() * 48
    const z = -22 + rnd() * 46
    if (Math.abs(x + 8) < 5.4 && Math.abs(z + 10) < 5.4) continue // 塔身
    if (Math.abs(x - 10) < 9.4 && Math.abs(z + 8) < 6.4) continue // 谷仓
    if (Math.abs(x + 10) < 5 && Math.abs(z - 13) < 4.4) continue // 小屋
    if (Math.abs(x + 2) < 4.4 && Math.abs(z - 10) < 3.2) continue // 打包机
    s.hay(x, z, 1.2 + rnd() * 0.5, 1.2 + rnd() * 0.5, rnd() < 0.5 ? 1.2 : 1.6)
  }

  // ---- 院子里的车辙石 / 木托盘（noCollide，0.08m）----
  for (let i = 0; i < 8; i++) {
    s.decal(-16 + rnd() * 34, -14 + rnd() * 30, 0.8 + rnd(), 0.3 + rnd() * 0.4, i % 2 === 0 ? 'wood' : 'stone')
  }

  set.list.push(...translate(s.list, ox, oz))
}
